#!/usr/bin/env python3
"""Pack props from the Dark Horror Asset pack tileset into Assets/props.png and bake Assets/ground.png.

usage: build_props.py <Dark_Horror_Asset_pack.png>
Also writes Sources/SquirrelFinder/PropAtlas.swift with each prop's pixel rect in the atlas.
The tileset's licence forbids redistributing it, so keep Assets/props.png and ground.png local.
"""
import random
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
src = Image.open(sys.argv[1]).convert("RGBA")

# name -> (x0, y0, x1, y1) in tileset pixels
PROPS = {
    "tombstone":   (2, 96, 20, 112),
    "crossSmall":  (20, 96, 34, 112),
    "crossBroken": (32, 96, 64, 128),
    "crossBig":    (64, 104, 96, 160),
    "crossBlood":  (104, 108, 128, 160),
    "treeGreen":   (80, 48, 112, 96),
    "treeDead":    (112, 48, 144, 96),
    "stump":       (144, 72, 170, 96),
    "bushBig":     (32, 48, 64, 80),
    "bushSmall":   (16, 48, 32, 64),
    "cauldron":    (64, 34, 108, 48),
    "mushroomA":   (0, 160, 16, 176),
    "mushroomB":   (16, 160, 32, 176),
    "mushroomC":   (32, 160, 48, 176),
    "pumpkin":     (48, 160, 64, 176),
    "torch":       (64, 160, 80, 176),
    "skull":       (288, 96, 304, 112),
    "bones":       (304, 96, 320, 112),
    "web":         (160, 96, 192, 128),
    "blood":       (192, 96, 208, 112),
    "spider":      (144, 96, 160, 114),
    "bat":         (128, 96, 144, 112),
}


def trim(im):
    bb = im.getchannel("A").point(lambda v: 255 if v > 8 else 0).getbbox()
    return im.crop(bb) if bb else im


# shelf-pack with 2 px padding so nearest sampling never bleeds between sprites
sprites = {k: trim(src.crop(r)) for k, r in PROPS.items()}
order = sorted(sprites, key=lambda k: -sprites[k].height)
atlas_w, x, y, shelf_h, pad = 256, 0, 0, 0, 2
placed = {}
for k in order:
    im = sprites[k]
    if x + im.width + pad > atlas_w:
        x, y, shelf_h = 0, y + shelf_h + pad, 0
    placed[k] = (x, y, im.width, im.height)
    x += im.width + pad
    shelf_h = max(shelf_h, im.height)
atlas_h = y + shelf_h + pad
atlas = Image.new("RGBA", (atlas_w, atlas_h), (0, 0, 0, 0))
for k, (px, py, w, h) in placed.items():
    atlas.paste(sprites[k], (px, py))
(ROOT / "Assets").mkdir(exist_ok=True)
atlas.save(ROOT / "Assets" / "props.png")

# ground: 12x12 tiles of dark moss (4 flip variants) plus sparse blades of grass
random.seed(7)
# tile (0,32) is an edge piece with transparent top rows, so use the solid one and its flips
base = src.crop((16, 32, 32, 48))
moss = [base, base.transpose(Image.FLIP_LEFT_RIGHT), base.transpose(Image.FLIP_TOP_BOTTOM),
        base.transpose(Image.ROTATE_180)]
blades = src.crop((0, 48, 16, 64))
N = 12
ground = Image.new("RGBA", (16 * N, 16 * N), (0, 0, 0, 255))
for ty in range(N):
    for tx in range(N):
        t = random.choice(moss)
        ground.alpha_composite(t, (tx * 16, ty * 16))
        if random.random() < 0.12:
            ground.alpha_composite(blades, (tx * 16, ty * 16))
ground.save(ROOT / "Assets" / "ground.png")

lines = [
    "// Generated by tools/build_props.py - do not edit.",
    "enum PropAtlas {",
    f"    static let size = SIMD2<Float>({atlas_w}, {atlas_h})",
    "    /// Pixel rects (x, y, w, h) of each prop inside Assets/props.png.",
    "    static let rects: [String: SIMD4<Float>] = [",
]
for k in sorted(placed):
    px, py, w, h = placed[k]
    lines.append(f'        "{k}": SIMD4({px}, {py}, {w}, {h}),')
lines += ["    ]", "}", ""]
(ROOT / "Sources" / "SquirrelFinder" / "PropAtlas.swift").write_text("\n".join(lines))
print("atlas", atlas.size, "props", len(placed))
for k in sorted(placed):
    print(f"  {k}: {placed[k][2]}x{placed[k][3]}")
